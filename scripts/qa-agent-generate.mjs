import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';

const root = process.cwd();
const manifestPath = path.join(root, 'docs/quality/d1-contracts.json');
const outputPath = path.join(root, 'e2e/D1-GENERATED.spec.ts');
const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'));
const allowedAuth = new Set(['guest', 'merchant', 'customer']);
const ids = new Set();

if (manifest.phase !== 'D1') throw new Error('Expected a D1 contract manifest.');
if (manifest.reviewed !== true) throw new Error('D1 manifest is not reviewed; refusing to generate tests.');
if (!Array.isArray(manifest.contracts) || !manifest.contracts.length) throw new Error('No D1 contracts found.');

for (const contract of manifest.contracts) {
  if (!contract.id || ids.has(contract.id)) throw new Error(`D1 contract id is missing or duplicated: ${contract.id}`);
  ids.add(contract.id);
  if (!contract.route?.startsWith('/')) throw new Error(`${contract.id}: route must be root-relative.`);
  if (!allowedAuth.has(contract.auth)) throw new Error(`${contract.id}: invalid auth mode ${contract.auth}`);
  if (!contract.selector) throw new Error(`${contract.id}: selector is required.`);
}

const hash = crypto.createHash('sha256').update(JSON.stringify(manifest)).digest('hex').slice(0, 16);
const lines = [
  '/* AUTO-GENERATED by scripts/qa-agent-generate.mjs.',
  ` * Contracts: ${path.relative(root, manifestPath)}`,
  ` * Manifest sha256: ${hash}`,
  ' * Reviewed volatile assertions are intentionally limited to route, selector,',
  ' * marker text, auth boundary and overflow. Add business assertions to a',
  ' * hand-written contract spec, not to this generated file.',
  ' */',
  "import { test, expect } from '@playwright/test';",
  "import { createMerchantFixture } from './helpers/d1-fixtures';",
  '',
  "test.describe('D1 generated route contracts', () => {"
];

for (const contract of manifest.contracts) {
  const fixture = contract.auth === 'merchant' || contract.auth === 'customer';
  const tokenSetup = contract.auth === 'merchant'
    ? "    await page.addInitScript((token) => localStorage.setItem('relaydesk_token', token), fixture.token);\n"
    : '';
  const routeExpr = contract.route.includes('<embed_key>')
    ? "contract.route.replace('<embed_key>', encodeURIComponent(fixture.site.embed_key))"
    : 'contract.route';
  const textAssertion = contract.text
    ? `    await expect(page.locator('body')).toContainText(${JSON.stringify(contract.text)});\n`
    : '';
  const authAssertion = contract.auth === 'merchant'
    ? "    await expect(page).not.toHaveURL(/\\/login\\.html/);\n"
    : '';
  lines.push(
    '',
    `  // ${contract.id} :: ${contract.criticality} :: ${contract.auth}`,
    `  test(${JSON.stringify(`D1 contract: ${contract.id}`)}, async ({ page, request }) => {`,
    `    const contract = ${JSON.stringify(contract)};`,
    "    const pageErrors: string[] = [];",
    "    page.on('pageerror', (error) => pageErrors.push(error.message));",
    fixture ? '    const fixture = await createMerchantFixture(request, "d1");' : '',
    tokenSetup,
    `    const response = await page.goto(${routeExpr}, { waitUntil: 'domcontentloaded' });`,
    "    expect(response?.status() ?? 0).toBeLessThan(400);",
    "    await expect(page.locator(contract.selector).first()).toBeVisible({ timeout: 15_000 });",
    textAssertion,
    authAssertion,
    "    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);",
    "    expect(overflow).toBe(false);",
    "    expect(pageErrors).toEqual([]);",
    '  });'
  );
}
lines.push('', '});', '');
await fs.writeFile(outputPath, lines.filter((line) => line !== '').join('\n'));
console.log(JSON.stringify({ manifest: path.relative(root, manifestPath), output: path.relative(root, outputPath), contracts: manifest.contracts.length, hash }, null, 2));

import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';

const root = process.cwd();
const evidencePath = path.join(root, 'artifacts/evidence/playwright-results.json');
const evidence = JSON.parse(await fs.readFile(evidencePath, 'utf8'));
const missing = evidence.tests.filter((test) => !test.screenshot);
if (!missing.length) {
  console.log(JSON.stringify({ cards: 0, message: 'All non-skipped tests already have screenshots.' }, null, 2));
  process.exit(0);
}
const outDir = path.join(root, 'artifacts/evidence/cards');
await fs.mkdir(outDir, { recursive: true });
const browser = await chromium.launch({
  headless: true,
  executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH || undefined
});
for (const [index, test] of missing.entries()) {
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const title = test.title.replace(/[<>&]/g, (ch) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;' }[ch]));
  const error = test.error ? `<pre>${test.error.replace(/[<>&]/g, (ch) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;' }[ch]))}</pre>` : '';
  await page.setContent(`<!doctype html><html><body style="margin:0;background:#f7f4ec;font-family:Arial,sans-serif;color:#262b33">
    <div style="border-top:10px solid #b84a1d;padding:44px 54px">
      <div style="font-size:14px;color:#6b6f76;letter-spacing:.08em">NUDGESO · TEST EVIDENCE CARD</div>
      <h1 style="font-size:30px;line-height:1.25;margin:18px 0 10px">${title}</h1>
      <div style="display:flex;gap:12px;margin:24px 0">
        <span style="background:#fdebdD;color:#7a3210;padding:8px 14px;border-radius:999px;font-weight:700">${test.status.toUpperCase()}</span>
        <span style="background:#fff;border:1px solid #e7dfcf;padding:8px 14px;border-radius:999px">${test.durationMs} ms</span>
        <span style="background:#fff;border:1px solid #e7dfcf;padding:8px 14px;border-radius:999px">${test.file}:${test.line}</span>
      </div>
      <p style="font-size:16px;color:#5b6470">This test drives API/context surfaces and intentionally does not keep a browser page open at teardown. The final page was not available, so this deterministic evidence card records the test identity and outcome. See the Playwright trace/JSON for the machine evidence.</p>
      ${error}
      <p style="margin-top:40px;font-size:13px;color:#7a7f86">Evidence generated by the D0–D5 QA pipeline · ${new Date().toISOString()}</p>
    </div>
  </body></html>`);
  const screenshotPath = path.join(outDir, `${String(index + 1).padStart(2, '0')}-${test.title.replace(/[^a-z0-9]+/gi, '-').slice(0, 80)}.png`);
  await page.screenshot({ path: screenshotPath, fullPage: false });
  await page.close();
  test.screenshot = screenshotPath;
}
await browser.close();
evidence.totals.withScreenshot = evidence.tests.filter((test) => test.screenshot).length;
await fs.writeFile(evidencePath, JSON.stringify(evidence, null, 2));
console.log(JSON.stringify({ cards: missing.length, evidencePath, withScreenshot: evidence.totals.withScreenshot }, null, 2));
